/**
 * Clinical Cohort Data & Risk Clustering Definitions
 * Provides population-level maternal-fetal risk mapping across the clinic registry.
 */

import { Patient } from '../types';

export type GestationalAgeTranche = '16-22w' | '23-27w' | '28-31w' | '32-35w' | '36-40w';

export type ClinicalPhenotype = 
  | 'ACCELERATED_DECLINE'   // Multi-factor placental failure (AFI drop + FGR)
  | 'FLUID_DECLINE'         // Oligohydramnios / Rapid AFI decay
  | 'GROWTH_DEVIATION'      // Fetal Growth Restriction (FGR / SGA)
  | 'VASCULAR_STRESS'       // Maternal Hypertensive / Placental Vascular Resistance
  | 'STABLE';               // Concordant physiological growth

export interface CohortPatient {
  id: string;
  mrn: string;
  name: string;
  age: number;
  gravidity: number;
  parity: number;
  gestationalAgeWeeks: number;
  gestationalAgeDays: number;
  assignedDoctorId: string;
  assignedDoctorName: string;
  status: 'HIGH' | 'WATCH' | 'LOW';
  trajectoryCategory: string;
  clinicalPhenotype: ClinicalPhenotype;
  gaTranche: GestationalAgeTranche;
  riskScore: number; // 0 - 100
  latestAfi: number; // cm
  afiVelocity: number; // cm/week (e.g. -0.85)
  latestGrowthPercentile: number; // % (e.g. 9%)
  growthVelocity: number; // %ile change per week (e.g. -3.2)
  latestEfw: number; // grams
  bloodPressure: string;
  recentNotes: string;
  primaryAlertFactor: string;
  isPrimaryDemoPatient: boolean;
}

export interface CohortCluster {
  id: string;
  title: string;
  codeName: string;
  urgency: 'CRITICAL_24H' | 'URGENT_72H' | 'MONITOR_7D' | 'ROUTINE';
  urgencyLabel: string;
  gaTranche: GestationalAgeTranche;
  clinicalPhenotype: ClinicalPhenotype;
  patientIds: string[];
  patientCount: number;
  avgRiskScore: number;
  pathophysiology: string;
  recommendedGuidelineAction: string;
  acogReference: string;
}

export interface HeatMapCell {
  gaTranche: GestationalAgeTranche;
  phenotype: ClinicalPhenotype;
  patients: CohortPatient[];
  count: number;
  avgRiskScore: number;
  heatLevel: 'critical' | 'high' | 'watch' | 'stable' | 'empty';
  clusterId?: string;
}

