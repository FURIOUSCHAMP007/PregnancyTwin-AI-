/**
 * Builds the complete 5x5 Heat Map Matrix from a population array
 */
export function buildCohortHeatMatrix(population: CohortPatient[]): HeatMapCell[][] {
  return CLINICAL_PHENOTYPES.map(pheno => {
    return GESTATIONAL_TRANCHES.map(tranche => {
      const cellPatients = population.filter(
        p => p.clinicalPhenotype === pheno.id && p.gaTranche === tranche.id
      );

      const count = cellPatients.length;
      const avgRiskScore = count > 0
        ? Math.round(cellPatients.reduce((sum, p) => sum + p.riskScore, 0) / count)
        : 0;

      let heatLevel: HeatMapCell['heatLevel'] = 'empty';
      if (count > 0) {
        if (avgRiskScore >= 80 || pheno.id === 'ACCELERATED_DECLINE') {
          heatLevel = 'critical';
        } else if (avgRiskScore >= 65 || pheno.id === 'FLUID_DECLINE') {
          heatLevel = 'high';
        } else if (avgRiskScore >= 45 || pheno.id === 'GROWTH_DEVIATION' || pheno.id === 'VASCULAR_STRESS') {
          heatLevel = 'watch';
        } else {
          heatLevel = 'stable';
        }
      }

      // Check if this cell belongs to any pre-identified cluster
      const matchedCluster = HIGH_RISK_CLUSTERS.find(
        c => c.clinicalPhenotype === pheno.id && c.gaTranche === tranche.id
      );

      return {
        gaTranche: tranche.id,
        phenotype: pheno.id,
        patients: cellPatients,
        count,
        avgRiskScore,
        heatLevel,
        clusterId: matchedCluster?.id
      };
    });
  });
}
