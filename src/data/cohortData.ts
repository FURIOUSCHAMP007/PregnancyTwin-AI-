export function determineGaTranche(weeks: number): GestationalAgeTranche {
  if (weeks < 23) return '16-22w';
  if (weeks <= 27) return '23-27w';
  if (weeks <= 31) return '28-31w';
  if (weeks <= 35) return '32-35w';
  return '36-40w';
}

